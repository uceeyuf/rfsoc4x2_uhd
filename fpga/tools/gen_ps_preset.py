#!/usr/bin/env python3
"""Extract the Zynq UltraScale+ PS preset (DDR, MIO, peripherals, PS clocks) from the
RFSoC 4x2 board files into a Tcl list, leaving out the PL-facing settings (AXI ports,
PL clocks, resets, interrupts, EMIO), which come from the X440 block design."""
import argparse
import re
import xml.etree.ElementTree as ET

PL_FACING = re.compile(
    r"PSU__(USE__|FPGA_PL|CRL_APB__PL\d|MAXIGP|SAXIGP|HIGH_ADDRESS|NUM_F2P|NUM_FABRIC|"
    r"IRQ_P2F|PL_CLK|GPIO_EMIO|PROTECTION|AFI\d|DDR_HIGH_ADDRESS)")

ap = argparse.ArgumentParser()
ap.add_argument("preset_xml")
ap.add_argument("out_tcl")
a = ap.parse_args()

root = ET.parse(a.preset_xml).getroot()
ps = next(p for p in root.iter("ip_preset")
          if p.get("preset_proc_name") == "zynq_ultra_ps_e_preset")
kv = []
for up in ps.iter("user_parameter"):
    name = up.get("name").replace("CONFIG.", "")
    if PL_FACING.match(name):
        continue
    kv.append((name, up.get("value")))

with open(a.out_tcl, "w") as f:
    f.write("# RFSoC 4x2 PS preset (DDR, MIO, peripherals, PS clocks), generated by\n"
            "# fpga/tools/gen_ps_preset.py from the RFSoC 4x2 board files (preset.xml,\n"
            "# Copyright (C) 2019 Xilinx Inc, Apache License 2.0).\n"
            "set rfsoc4x2_ps_preset [list \\\n")
    for k, v in kv:
        f.write(f"  CONFIG.{k} {{{v}}} \\\n")
    f.write("]\n")
print(len(kv), "settings")
