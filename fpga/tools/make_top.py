#!/usr/bin/env python3
"""Generate fpga/rfsoc4x2.sv from the upstream X4xx top level (uhd/fpga/usrp3/
top/x400/x4xx.sv): keep the X440 / RF_CORE_FULL / QSFP0 path (unifdef.py), then
apply the RFSoC 4x2 board differences below. Every edit must match exactly once,
so an upstream change shows up as an error here instead of a silent mismatch.

  fpga/tools/make_top.py            # writes fpga/rfsoc4x2.sv
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "uhd", "fpga", "usrp3", "top", "x400", "x4xx.sv")
DST = os.path.join(ROOT, "fpga", "rfsoc4x2.sv")

DEFS = ["X440", "RF_CORE_FULL"]
UNDEFS = ["X410", "X420", "RF_CORE_100M", "RF_CORE_200M", "RF_CORE_400M",
          "RF_CORE_1000M", "QSFP1_0", "QSFP1_1", "QSFP1_2", "QSFP1_3",
          "IPASS0_LANES", "IPASS1_LANES", "DISABLE_TX"]

args = [sys.executable, os.path.join(HERE, "unifdef.py")]
for d in DEFS:
    args += ["-D", d]
for u in UNDEFS:
    args += ["-U", u]
s = subprocess.run(args, stdin=open(SRC), capture_output=True, text=True, check=True).stdout


def sub(old, new, count=1, regex=False):
    """Replace old by new; old must occur exactly `count` times."""
    global s
    n = len(re.findall(old, s, flags=re.S)) if regex else s.count(old)
    if n != count:
        raise SystemExit(f"expected {count} match(es), found {n}:\n{old[:200]}")
    s = re.sub(old, new, s, flags=re.S) if regex else s.replace(old, new)


# ---------------------------------------------------------------------------
# Header and port list
# ---------------------------------------------------------------------------
sub("""//
// Copyright 2021 Ettus Research, A National Instruments Brand
//
// SPDX-License-Identifier: LGPL-3.0-or-later
//
// Module: x4xx
//
// Description: Top-level module for X410 devices.
//
""", """//
// Copyright 2021 Ettus Research, A National Instruments Brand
// Copyright 2026 Yijie Yu (RFSoC 4x2 port)
//
// SPDX-License-Identifier: LGPL-3.0-or-later
//
// Module: rfsoc4x2
//
// Description: Top-level module for the RFSoC 4x2 (xczu48dr), generated by
//   fpga/tools/make_top.py from the X440 path of the UHD X4xx top level
//   (x4xx.sv). Do not edit by hand; change make_top.py instead.
//
//   Differences to the X440:
//   - RFDC: refclk only on ADC 226 / DAC 230 (500 MHz from the LMX2594s), see
//     ip/rfsoc4x2_ps_rfdc_bd. DB0 = radio0 = ADC 224/225, DAC 228/229;
//     DB1 = radio1 = ADC 226/227, DAC 230/231. Bonded on the board: DB0_RX[1:0]
//     (ADC_C/ADC_D), DB1_RX[1:0] (ADC_A/ADC_B), DB0_TX[0] (DAC_A), DB1_TX[0]
//     (DAC_B).
//   - PLL_REFCLK_FPGA = LMK04828 FPGA_REFCLK_IN (500 MHz), SYSREF_FABRIC =
//     LMK04828 SYS_REF_FPGA. pll_ref_clk (data clock MMCM) is 125 MHz; the
//     base reference clock (PPS generation) is pll_ref_clk / 5 = 25 MHz.
//   - One QSFP28 (QSFP0, 100 GbE), refclk QSFP0_REFCLK (156.25 MHz).
//   - No motherboard / daughterboard CPLDs, DB GPIO, DIO, GPS, PPS input,
//     trigger I/O, DRAM, iPass or eCPRI clock output: the related logic is kept
//     (MPM register map) with its pins tied off inside.
//
""")

port_start = s.index("module x4xx (")
port_end = s.index(");", port_start) + 2
s = s[:port_start] + """module rfsoc4x2 (
  //-----------------------------------
  // RF block signals
  //-----------------------------------

  // Clocking and sync (LMK04828 / LMX2594)
  input  wire       SYSREF_RF_P,
  input  wire       SYSREF_RF_N,
  input  wire       ADC_CLK_P,      // ADC tile 226 refclk
  input  wire       ADC_CLK_N,
  input  wire       DAC_CLK_P,      // DAC tile 230 refclk
  input  wire       DAC_CLK_N,

  // Analog ports (see header for the bonded ones)
  input  wire [3:0] DB0_RX_P,
  input  wire [3:0] DB0_RX_N,
  input  wire [3:0] DB1_RX_P,
  input  wire [3:0] DB1_RX_N,
  output wire [3:0] DB0_TX_P,
  output wire [3:0] DB0_TX_N,
  output wire [3:0] DB1_TX_P,
  output wire [3:0] DB1_TX_N,

  //-----------------------------------
  // QSFP28 (GTY X0Y4..X0Y7, placed by the CMAC IP)
  //-----------------------------------

  input  wire QSFP0_REFCLK_P,       // 156.25 MHz
  input  wire QSFP0_REFCLK_N,
  `ifdef QSFP0_0
  input  wire QSFP0_0_RX_P,
  input  wire QSFP0_0_RX_N,
  output wire QSFP0_0_TX_P,
  output wire QSFP0_0_TX_N,
  `endif
  `ifdef QSFP0_1
  input  wire QSFP0_1_RX_P,
  input  wire QSFP0_1_RX_N,
  output wire QSFP0_1_TX_P,
  output wire QSFP0_1_TX_N,
  `endif
  `ifdef QSFP0_2
  input  wire QSFP0_2_RX_P,
  input  wire QSFP0_2_RX_N,
  output wire QSFP0_2_TX_P,
  output wire QSFP0_2_TX_N,
  `endif
  `ifdef QSFP0_3
  input  wire QSFP0_3_RX_P,
  input  wire QSFP0_3_RX_N,
  output wire QSFP0_3_TX_P,
  output wire QSFP0_3_TX_N,
  `endif

  input  wire QSFP0_MODPRS_n,
  output wire QSFP0_RESET_n,
  output wire QSFP0_LPMODE,
  output wire QSFP0_MODSEL_n,

  //-----------------------------------
  // PL clocks from the LMK04828
  //-----------------------------------

  input  wire PLL_REFCLK_FPGA_P,
  input  wire PLL_REFCLK_FPGA_N,
  input  wire SYSREF_FABRIC_P,
  input  wire SYSREF_FABRIC_N
);
""" + s[port_end:]

# ---------------------------------------------------------------------------
# Clocks
# ---------------------------------------------------------------------------
sub("""  assign DB0_SYNTH_SYNC = 1'b0;
  assign DB1_SYNTH_SYNC = 1'b0;

""", "")
sub("""  // Buffer the incoming base reference clock
  IBUFGDS ibufgds_base_ref_clk (
    .O  (base_ref_clk),
    .I  (BASE_REFCLK_FPGA_P),
    .IB (BASE_REFCLK_FPGA_N)
  );
""", """  // Base reference clock (PPS generation): no separate reference on the
  // RFSoC 4x2, so divide the PLL reference: 125 MHz / 5 = 25 MHz.
  BUFGCE_DIV #(
    .BUFGCE_DIVIDE(5),
    .SIM_DEVICE("ULTRASCALE_PLUS")
  ) bufgce_div_base_ref_clk (
    .I   (pll_ref_clk),
    .CLR (1'b0),
    .CE  (1'b1),
    .O   (base_ref_clk)
  );
""")
# 5 MHz sync clock: only for X440 daughterboard LO sync
sub(r"  // Need a 5 MHz pulse on X440 to use as a sync ref\n    wire clk5;\n\n    BUFGCE_DIV #\(.*?\) clock_div_5mhz \(.*?\);\n",
    "  // No daughterboard LO sync clock on the RFSoC 4x2\n  wire clk5 = 1'b0;\n", regex=True)

# Clocking watchdog (ENABLE_CLOCK_WD is 0 for this board; its monitor clock
# was an X4xx MGT reference)
sub(r"  if \(`ENABLE_CLOCK_WD\) begin : gen_clock_wd.*?end else begin : gen_no_clock_wd\n    assign rfdc_clk_fault = '0;\n  end\n",
    "  assign rfdc_clk_fault = '0;\n", regex=True)

# ---------------------------------------------------------------------------
# PPS, trigger I/O
# ---------------------------------------------------------------------------
sub("""    .pps_in           (PPS_IN),""", """    .pps_in           (1'b0),""")
sub("""    .sync             (LMK_SYNC),""", """    .sync             (),""")
sub("""  wire [1:0] trig_io_select;
  assign TRIG_IO = (trig_io_select == TRIG_IO_PPS_OUTPUT) ? pps_refclk : 1'bz;
  assign PPS_LED = pps_refclk;
""", """  wire [1:0] trig_io_select;  // no trigger I/O / PPS LED on the RFSoC 4x2
""")

# ---------------------------------------------------------------------------
# PS GPIO
# ---------------------------------------------------------------------------
sub("""  assign gpio_0_tri_i[29]    = QSFP1_MODPRS_n;""", """  assign gpio_0_tri_i[29]    = 1'b1;  // no QSFP1""")
sub("""  assign CPLD_JTAG_OE_n = gpio_0_tri_o[0];""", "")
sub("""  assign PL_CPLD_JTAGEN = gpio_0_tri_o[1];""", "")

# ---------------------------------------------------------------------------
# PS + RFDC block design
# ---------------------------------------------------------------------------
sub("x440_ps_rfdc_bd x440_ps_rfdc_bd_i (", "rfsoc4x2_ps_rfdc_bd rfsoc4x2_ps_rfdc_bd_i (")
sub(r"      \.adc0_clk_clk_n .*?\.adc3_clk_clk_p                \(ADC_CLK_P\[3\]\),\n",
    """      .adc2_clk_clk_n                (ADC_CLK_N),
      .adc2_clk_clk_p                (ADC_CLK_P),
""", regex=True)
sub(r"      \.dac0_clk_clk_n .*?\.dac1_clk_clk_p                \(DAC_CLK_P\[1\]\),\n",
    """      .dac2_clk_clk_n                (DAC_CLK_N),
      .dac2_clk_clk_p                (DAC_CLK_P),
""", regex=True)
vout = ""
for db, tiles in ((0, (228, 229)), (1, (230, 231))):
    for i, (t, c) in enumerate([(tiles[0], 0), (tiles[0], 1), (tiles[1], 0), (tiles[1], 1)]):
        for pol in ("n", "p"):
            name = f".dac_tile{t}_ch{c}_vout_v_{pol}"
            vout += f"      {name:<31}(DB{db}_TX_{pol.upper()}[{i}]),\n"
sub(r"      \.dac_tile228_ch0_vout_v_n .*?\.dac_tile229_ch3_vout_v_p      \(DB1_TX_P\[3\]\),\n",
    vout, regex=True)

# ---------------------------------------------------------------------------
# Daughterboard GPIO / sync clock: no daughterboards
# ---------------------------------------------------------------------------
sub("""      // The sync_clk flip-flop is driven in single-ended mode. The _n side is
      // set statically via a voltage divider with DB0_GPIO[12] and
      // DB1_GPIO[16] providing the source voltages.
      assign DB0_GPIO[12] = 1'b1;
      assign DB0_GPIO[13] = sync_clk[0];
      assign DB1_GPIO[16] = 1'b1;
      assign DB1_GPIO[17] = sync_clk[1];
""", "")
sub(r"      // on X440, some gpio are used to drive sync clk, and not tri-state\.\n      for \(db_gpio_i = 0;.*?\n      end\n",
    "      // No daughterboard GPIO pins on the RFSoC 4x2\n", regex=True)
sub("""      .db0_gpio_in_ext     (DB0_GPIO),""", """      .db0_gpio_in_ext     (20'b0),""")
sub("""      .db1_gpio_in_ext     (DB1_GPIO),""", """      .db1_gpio_in_ext     (20'b0),""")

# ---------------------------------------------------------------------------
# QSFP sideband
# ---------------------------------------------------------------------------
sub("""  assign QSFP0_RESET_n  = 1'b1;   // Module reset
  assign QSFP0_LPMODE_n = 1'b0;   // Low-power Mode
  assign QSFP1_RESET_n  = 1'b1;   // Module reset
  assign QSFP1_LPMODE_n = 1'b0;   // Low-power Mode
""", """  assign QSFP0_RESET_n  = 1'b1;   // Module reset (inactive)
  assign QSFP0_LPMODE   = 1'b0;   // High-power mode
  assign QSFP0_MODSEL_n = 1'b0;   // Module selected (I2C)
""")

# ---------------------------------------------------------------------------
# CPLD interface: no CPLD
# ---------------------------------------------------------------------------
sub("""    .ss                      ({PL_CPLD_CS1_n, PL_CPLD_CS0_n}),
    .sclk                    (PL_CPLD_SCLK),
    .mosi                    (PL_CPLD_MOSI),
    .miso                    (PL_CPLD_MISO),""", """    .ss                      (),
    .sclk                    (),
    .mosi                    (),
    .miso                    (1'b0),""")

# ---------------------------------------------------------------------------
# DIO: none
# ---------------------------------------------------------------------------
sub(r"  // The bit positions in the DIOA_FPGA IO port.*?end endgenerate\n",
    """  // No DIO on the RFSoC 4x2
  assign gpio_in_a = 12'b0;
  assign gpio_in_b = 12'b0;
""", regex=True)

# ---------------------------------------------------------------------------
# x4xx_core: DRAM, QSFP reference clocks, aux reference
# ---------------------------------------------------------------------------
for b in (0, 1):
    sub(f"    .dram{b}_sys_clk_p               (DRAM{b}_REFCLK_P),", f"    .dram{b}_sys_clk_p               (1'b0),")
    sub(f"    .dram{b}_sys_clk_n               (DRAM{b}_REFCLK_N),", f"    .dram{b}_sys_clk_n               (1'b1),")
    sub(rf"(    \.dram{b}_(?:ck_t|ck_c|cs_n|act_n|adr|ba|bg|cke|odt|reset_n|dm_dbi_n|dq|dqs_t|dqs_c)\s+)\(DRAM{b}_\w+\),",
        r"\1(),", count=14, regex=True)
sub("""    .qsfp0_refclk_p                (MGT_REFCLK_LMK0_P),
    .qsfp0_refclk_n                (MGT_REFCLK_LMK0_N),""", """    .qsfp0_refclk_p                (QSFP0_REFCLK_P),
    .qsfp0_refclk_n                (QSFP0_REFCLK_N),""")
sub("""    .qsfp1_refclk_p                (MGT_REFCLK_LMK3_P),
    .qsfp1_refclk_n                (MGT_REFCLK_LMK3_N),""", """    .qsfp1_refclk_p                (1'b0),
    .qsfp1_refclk_n                (1'b1),""")
sub("""    .fpga_aux_ref                  (FPGA_AUX_REF),""", """    .fpga_aux_ref                  (1'b0),""")

# ---------------------------------------------------------------------------
# eCPRI clock output: none
# ---------------------------------------------------------------------------
sub(r"  //-+\n  // eCPRI Clock Output Test\n  //-+\n.*?\n(endmodule)",
    r"\1", regex=True)

open(DST, "w").write(s)
print(f"wrote {DST} ({s.count(chr(10))} lines)")
